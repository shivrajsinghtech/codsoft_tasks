"""Train, compare and save the Spam SMS Detection models.

Usage:
    python train.py

Steps
-----
1. Load and clean ``data/spam.csv``.
2. Exploratory data analysis (figures -> ``reports/figures``).
3. Stratified 80/20 train/test split.
4. For each of Naive Bayes, Logistic Regression and SVM, tune a TF-IDF +
   classifier pipeline with stratified 5-fold CV on the TRAINING set only.
5. Evaluate every tuned pipeline once on the held-out test set.
6. Select the best model by cross-validated spam F1 (balances spam recall
   and precision), save the full pipeline with joblib and write reports.
"""

import json
import time
from datetime import datetime, timezone

import joblib
import pandas as pd
import sklearn
from sklearn.model_selection import GridSearchCV, StratifiedKFold, train_test_split

from src import config
from src.data_preprocessing import clean_dataset, load_raw_data
from src.eda import run_eda
from src.evaluation import (
    compute_metrics,
    plot_confusion_matrix,
    plot_model_comparison,
    text_report,
)
from src.models import PARAM_GRIDS, build_pipelines


def split_data(df: pd.DataFrame):
    return train_test_split(
        df["message"], df["target"],
        test_size=config.TEST_SIZE,
        stratify=df["target"],
        random_state=config.RANDOM_STATE,
    )


def tune_and_evaluate(name, pipeline, X_train, y_train, X_test, y_test, cv):
    search = GridSearchCV(
        pipeline,
        PARAM_GRIDS[name],
        scoring={"f1": "f1", "recall": "recall", "precision": "precision", "accuracy": "accuracy"},
        refit="f1",
        cv=cv,
        n_jobs=-1,
    )
    start = time.perf_counter()
    search.fit(X_train, y_train)
    train_seconds = time.perf_counter() - start

    best = search.best_estimator_
    i = search.best_index_
    cv_scores = {
        f"cv_{m}": round(float(search.cv_results_[f"mean_test_{m}"][i]), 4)
        for m in ["accuracy", "precision", "recall", "f1"]
    }
    y_pred = best.predict(X_test)
    y_proba = best.predict_proba(X_test)[:, list(best.classes_).index(1)]
    metrics = compute_metrics(y_test, y_pred, y_proba)
    metrics.update(cv_scores)
    metrics["best_params"] = {k: v for k, v in search.best_params_.items()}
    metrics["tuning_seconds"] = round(train_seconds, 2)
    return best, metrics, text_report(y_test, y_pred)


def write_markdown_report(summary, eda, results, reports, best_name, split_info, path):
    lines = [
        "# Spam SMS Detection - Model Evaluation Report",
        "",
        f"_Generated by `train.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}_",
        "",
        "## Dataset",
        "",
        f"- Raw rows: **{summary['raw_rows']}**",
        f"- Rows whose message overflowed into unnamed columns (text merged back): "
        f"**{summary['rows_with_overflow_text']}**",
        f"- Dropped columns: {', '.join(summary['dropped_columns']) or 'none'}",
        f"- Missing rows removed: **{summary['missing_rows_removed']}**",
        f"- Duplicate rows removed: **{summary['duplicate_rows_removed']}**",
        f"- Clean rows: **{summary['clean_rows']}** "
        f"(ham: {summary['class_counts'].get('ham', 0)}, spam: {summary['class_counts'].get('spam', 0)})",
        f"- Train / test (stratified): **{split_info['train_size']} / {split_info['test_size']}** "
        f"(spam in test: {split_info['test_spam']})",
        "",
        "### Average message statistics by class",
        "",
        "| Class | Characters | Words | Digits | Upper-case ratio |",
        "|---|---|---|---|---|",
    ]
    for label, s in eda["length_summary"].items():
        lines.append(f"| {label} | {s['char_count']} | {s['word_count']} | "
                     f"{s['digit_count']} | {s['upper_ratio']} |")
    lines += [
        "",
        "## Test-set results (SPAM = positive class)",
        "",
        "| Model | Accuracy | Precision (spam) | Recall (spam) | F1 (spam) | ROC-AUC | CV F1 (train) |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, m in results.items():
        mark = " **(selected)**" if name == best_name else ""
        lines.append(
            f"| {name}{mark} | {m['accuracy']:.4f} | {m['precision_spam']:.4f} | "
            f"{m['recall_spam']:.4f} | {m['f1_spam']:.4f} | {m['roc_auc']:.4f} | {m['cv_f1']:.4f} |"
        )
    lines += ["", "## Confusion matrices (test set)", ""]
    for name, m in results.items():
        lines += [
            f"**{name}** - TN={m['tn']}, FP={m['fp']} (legitimate flagged as spam), "
            f"FN={m['fn']} (spam missed), TP={m['tp']}",
            "",
        ]
    lines += ["## Per-model classification reports", ""]
    for name, rep in reports.items():
        lines += [f"### {name}", "", f"Best hyper-parameters: `{results[name]['best_params']}`",
                  "", "```", rep.rstrip(), "```", ""]
    lines += [
        "## Model selection",
        "",
        f"Selected model: **{best_name}**.",
        "",
        "Selection used the mean spam F1-score from stratified 5-fold cross-validation "
        "on the training set, so the test set was never used to choose a model. "
        "F1 was preferred over raw recall because a model that flags every message "
        "would have perfect spam recall but be useless; F1 rewards catching spam "
        "while keeping legitimate messages out of the spam folder.",
        "",
        "## Figures",
        "",
        "![Class distribution](figures/class_distribution.png)",
        "![Message length](figures/message_length_distribution.png)",
        "![Top words](figures/top_words.png)",
        "![Model comparison](figures/model_comparison.png)",
    ]
    for name in results:
        lines.append(f"![{name} confusion matrix](figures/{_slug(name)}_confusion_matrix.png)")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _slug(name: str) -> str:
    return name.lower().replace(" ", "_")


def main() -> dict:
    for d in (config.MODELS_DIR, config.FIGURES_DIR, config.PROCESSED_DATA_PATH.parent):
        d.mkdir(parents=True, exist_ok=True)

    print("== Phase 1: data preprocessing ==")
    raw = load_raw_data()
    print(f"Raw shape: {raw.shape}; columns: {list(raw.columns)}")
    df, summary = clean_dataset(raw)
    df.to_csv(config.PROCESSED_DATA_PATH, index=False)
    print(json.dumps(summary, indent=2))

    eda = run_eda(df, config.FIGURES_DIR)
    print("Average stats by class:\n", pd.DataFrame(eda["length_summary"]).T)

    print("\n== Phase 2: machine learning ==")
    X_train, X_test, y_train, y_test = split_data(df)
    split_info = {
        "train_size": int(len(X_train)), "test_size": int(len(X_test)),
        "train_spam": int(y_train.sum()), "test_spam": int(y_test.sum()),
    }
    print(split_info)

    cv = StratifiedKFold(n_splits=config.CV_FOLDS, shuffle=True, random_state=config.RANDOM_STATE)
    fitted, results, reports = {}, {}, {}
    for name, pipe in build_pipelines().items():
        model, metrics, report = tune_and_evaluate(name, pipe, X_train, y_train, X_test, y_test, cv)
        fitted[name], results[name], reports[name] = model, metrics, report
        plot_confusion_matrix(metrics["confusion_matrix"], f"{name} (test set)",
                              config.FIGURES_DIR / f"{_slug(name)}_confusion_matrix.png")
        print(f"\n--- {name} --- best params: {metrics['best_params']}")
        print(f"CV (train) F1={metrics['cv_f1']}  recall={metrics['cv_recall']}")
        print(report)
        print("Confusion matrix [[TN, FP], [FN, TP]]:", metrics["confusion_matrix"])

    best_name = max(results, key=lambda n: (results[n]["cv_f1"], results[n]["cv_recall"]))
    best_model = fitted[best_name]
    print(f"\nSelected model (highest CV spam F1): {best_name}")

    plot_model_comparison(results, config.FIGURES_DIR / "model_comparison.png")
    plot_confusion_matrix(results[best_name]["confusion_matrix"],
                          f"Selected: {best_name}", config.FIGURES_DIR / "best_model_confusion_matrix.png")

    joblib.dump(best_model, config.MODEL_PATH, compress=3)
    print(f"Saved pipeline to {config.MODEL_PATH.relative_to(config.ROOT_DIR)}")

    comparison = pd.DataFrame(results).T[
        ["accuracy", "precision_spam", "recall_spam", "f1_spam", "roc_auc",
         "cv_accuracy", "cv_precision", "cv_recall", "cv_f1", "tn", "fp", "fn", "tp"]
    ]
    comparison.index.name = "model"
    comparison.to_csv(config.COMPARISON_PATH)

    payload = {
        "best_model": best_name,
        "selection_criterion": "highest mean 5-fold CV spam F1 on training set",
        "trained_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "sklearn_version": sklearn.__version__,
        "data_summary": summary,
        "split": split_info,
        "models": results,
    }
    config.METRICS_PATH.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    (config.REPORTS_DIR / "classification_reports.txt").write_text(
        "\n".join(f"=== {n} ===\n{r}" for n, r in reports.items()), encoding="utf-8"
    )
    write_markdown_report(summary, eda, results, reports, best_name, split_info, config.REPORT_MD_PATH)
    print("\nModel comparison (test set):")
    print(comparison[["accuracy", "precision_spam", "recall_spam", "f1_spam", "cv_f1"]].to_string())
    return payload


if __name__ == "__main__":
    main()
